export type IconName = keyof typeof ICONS;

/** An icon sized to the surrounding text. Decorative by default (hidden from screen readers); pass `label` if it stands alone. */
export function Icon({ name, size = "1.1em", label, className = "" }: { name: IconName; size?: number | string; label?: string; className?: string }) {
  const C = ICONS[name];
  return <C className={`icon ${className}`.trim()} size={size} strokeWidth={1.75} aria-hidden={label ? undefined : true} aria-label={label} role={label ? "img" : undefined} focusable={false} />;
}
