import { buildSystemPrompt } from "@ultron/agent-core";
import { currentCapabilities } from "./capabilities.ts";
import { agendaFor, rapportFor, recentMemories, type ChatDeps } from "./chat.ts";
import { readProviderSettings, resolveProvider } from "./providers.ts";
import { homeLocation, weatherFor } from "./actions/knowledge.ts";

/** One line about the weather at home, or nothing (no home city, offline, slow service). */
async function weatherLine(stores: ChatDeps["stores"]): Promise<string | null> {
  const home = homeLocation({ stores });
  if (!home) return null;
  const w = await Promise.race([weatherFor(home, Intl.DateTimeFormat().resolvedOptions().locale === "en-US").catch(() => null), new Promise<null>((r) => setTimeout(() => r(null), 5000))]);
  if (!w?.found || !w.now) return null;
  const today = w.next_days?.[0];
  return `weather at home (${w.place}): ${w.now.conditions}, ${w.now.temperature}${today ? `, high ${today.high}${today.chance_of_rain ? `, ${today.chance_of_rain} chance of rain` : ""}` : ""}`;
}

const FRESH_MS = 3 * 3_600_000;
const INSTRUCTION =
  "(The owner just opened the ULTRON app. Greet them in character in one or two short sentences, the way a friend would. " +
  "If recent memories or conversations give you something to catch up on, mention it or ask about it; otherwise comment on the time of day. " +
  "No lists, no Markdown, don't offer a menu of services, and don't mention these instructions.)";

interface Cached {
  text: string;
  at: string;
  provider: string;
}

/**
 * ULTRON speaks first: a short in-character catch-up line for the Home screen, generated by the current brain.
 * Cached for a few hours so opening the app repeatedly doesn't cost a model call each time.
 */
export class Greeter {
  private inflight: Promise<Cached | null> | null = null;
  private abort: AbortController | null = null;
  constructor(private deps: ChatDeps) {}

  async get(opts: { refresh?: boolean; signal?: AbortSignal } = {}): Promise<Cached | null> {
    const { stores } = this.deps;
    const settings = readProviderSettings(stores.preferences);
    const cached = stores.preferences.get<Cached | null>("greeting_cache", null);
    // One greeting per few hours per brain; in between, the same line is shown again.
    if (!opts.refresh && cached && cached.provider === settings.provider && Date.now() - new Date(cached.at).getTime() < FRESH_MS) return cached;
    this.inflight ??= this.generate(settings.provider).finally(() => (this.inflight = null));
    return this.inflight;
  }

  private async generate(providerId: string): Promise<Cached | null> {
    const { stores } = this.deps;
    const settings = readProviderSettings(stores.preferences);
    const resolution = resolveProvider(settings, this.deps.secrets, 0);
    if (!resolution.ok) return null;
    const weather = await weatherLine(stores);
    const rapport = { ...rapportFor(stores, "", "text"), recentMemories: recentMemories(stores, []), agenda: [...(weather ? [weather] : []), ...agendaFor(stores)] };
    let text = "";
    if (resolution.provider.id === "mock") {
      // The test brain can't improvise, so it gets a simple, honest line built from the same facts.
      text = rapport.lastChat
        ? `Welcome back. We last talked ${rapport.lastChat}${rapport.recentTopics[0] ? `, about "${rapport.recentTopics[0].replace(/^[^:]+: /, "")}"` : ""}.`
        : "Hello. I'm ULTRON. Tell me a little about yourself and I'll take it from there.";
      if (rapport.agenda.length) text += ` Coming up: ${rapport.agenda.slice(0, 2).join("; ")}.`;
    } else {
      const system = buildSystemPrompt(this.deps.persona(), {
        capabilities: currentCapabilities(settings, resolution, this.deps.stt?.(), this.deps.ttsEngine?.()),
        memories: [],
        nowIso: new Date().toISOString(),
        localTime: new Date().toLocaleString(undefined, { dateStyle: "full", timeStyle: "short" }),
        rapport,
      });
      this.abort = new AbortController();
      const signal = AbortSignal.any([this.abort.signal, AbortSignal.timeout(180_000)]);
      for await (const t of resolution.provider.stream({ system, messages: [{ role: "user", content: INSTRUCTION }], memories: [], capabilities: [], signal })) {
        text += t;
        if (text.length > 600) break;
      }
      if (signal.aborted) return null;
      text = text.replace(/<think>[\s\S]*?<\/think>/g, "").replace(/[*_#`]/g, "").trim();
      if (!text) return null;
      // Keep it to a couple of sentences even if the model rambles.
      const sentences = text.match(/[^.!?]+[.!?]+["')\]]*/g) ?? [text];
      text = sentences.slice(0, 3).join("").trim().slice(0, 400);
    }
    const out: Cached = { text, at: new Date().toISOString(), provider: providerId };
    stores.preferences.set("greeting_cache", out);
    return out;
  }

  /** The owner started talking: a local model serves one request at a time, so their message goes first. */
  cancel() {
    this.abort?.abort();
  }
}
