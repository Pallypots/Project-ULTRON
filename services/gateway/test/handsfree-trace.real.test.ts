// Full end-to-end trace of a hands-free conversation against a REAL ULTRON service process with the REAL on-PC speech
// models (Whisper to listen, Kokoro to speak). Watches the service's health every 250 ms the whole time.
//
// Positive controls (must happen): addressed speech is understood and answered aloud; follow-ups work without the wake
// word; the service stays online throughout; a crash of the speech model is survived.
// Negative controls (must NOT happen / must be detected): speech not addressed to ULTRON is discarded; the health
// monitor really does notice when the service goes down (so "it stayed online" means something).
//
// Downloads models, so it only runs with ULTRON_TEST_TTS=1 (CI).
import { spawn, execFileSync, type ChildProcess } from "node:child_process";
import { mkdirSync, mkdtempSync, symlinkSync } from "node:fs";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { encodeWav, resample } from "@ultron/audio";
import { KokoroEngine } from "../src/tts/kokoro.ts";
import { ciNote } from "./helpers.ts";

const enabled = process.env.ULTRON_TEST_TTS === "1";
const modelDir = process.env.ULTRON_TEST_MODEL_DIR ?? join(tmpdir(), "ultron-test-models");
const root = join(import.meta.dirname, "../../..");

const freePort = () => new Promise<number>((r) => { const s = createServer(); s.listen(0, "127.0.0.1", () => { const p = (s.address() as { port: number }).port; s.close(() => r(p)); }); });

function childPids(pid: number): number[] {
  try {
    if (process.platform === "win32") {
      const out = execFileSync("powershell.exe", ["-NoProfile", "-Command", `(Get-CimInstance Win32_Process -Filter "ParentProcessId = ${pid}").ProcessId`]).toString();
      return out.split(/\s+/).filter(Boolean).map(Number);
    }
    return execFileSync("ps", ["-o", "pid=", "--ppid", String(pid)]).toString().split(/\s+/).filter(Boolean).map(Number);
  } catch {
    return [];
  }
}

describe.skipIf(!enabled)("hands-free conversation, traced end to end (real service, real speech models)", () => {
  it("stays online and keeps the conversation going; ignores what isn't for it; survives a speech-model crash", async () => {
    // Speech to "say" to ULTRON, generated by the local voice (in this test process, not the service).
    const kokoro = new KokoroEngine(modelDir);
    const say = async (text: string) => {
      const { samples, sampleRate } = await kokoro.synthesize(text, "bm_george", 1);
      return encodeWav(resample(samples, sampleRate));
    };
    const addressed = await say("Ultron, what time is it?");
    const notForUs = await say("I was telling my sister about the weather yesterday.");
    const followUp = await say("Thanks. What time is it now?");
    kokoro.host.stop();

    // A real ULTRON service, using the same model files.
    const dataDir = mkdtempSync(join(tmpdir(), "ultron-trace-"));
    mkdirSync(modelDir, { recursive: true });
    symlinkSync(modelDir, join(dataDir, "models"), "junction");
    const port = await freePort();
    const base = `http://localhost:${port}`;
    const server: ChildProcess = spawn(process.execPath, ["--disable-warning=ExperimentalWarning", "--import", "tsx", "services/gateway/src/main.ts"], {
      cwd: root,
      env: { ...process.env, ULTRON_PORT: String(port), ULTRON_DATA_DIR: dataDir, ULTRON_PROVIDER: "mock", ULTRON_EMBEDDINGS: "off", ULTRON_CHECKIN: "off", ULTRON_WATCHERS: "off", ULTRON_LOG_LEVEL: "warn", ULTRON_STT_ENGINE: "local", ULTRON_TTS_ENGINE: "local" },
      stdio: ["ignore", "inherit", "inherit"],
    });
    const trace: string[] = [];
    const log = (s: string) => trace.push(`${((Date.now() - t0) / 1000).toFixed(1)}s ${s}`);
    const t0 = Date.now();
    try {
      for (let i = 0; i < 120; i++) {
        if (await fetch(`${base}/api/health`).then((r) => r.ok, () => false)) break;
        await new Promise((r) => setTimeout(r, 500));
      }
      log("service up");
      const { token } = (await (await fetch(`${base}/api/bootstrap`)).json()) as { token: string };
      const auth = { authorization: `Bearer ${token}` };

      // Health monitor: every 250 ms, 2 s timeout.
      const health = { checks: 0, failures: 0, maxMs: 0 };
      let monitoring = true;
      const monitor = (async () => {
        while (monitoring) {
          const s = Date.now();
          const ok = await fetch(`${base}/api/health`, { signal: AbortSignal.timeout(2000) }).then((r) => r.ok, () => false);
          health.checks++;
          if (!ok) health.failures++;
          health.maxMs = Math.max(health.maxMs, Date.now() - s);
          await new Promise((r) => setTimeout(r, 250));
        }
      })();

      const hear = async (wav: Uint8Array, wake: boolean) => {
        const r = await fetch(`${base}/api/voice/transcribe${wake ? "?mode=wake" : ""}`, { method: "POST", headers: { ...auth, "content-type": "audio/wav" }, body: wav as BodyInit });
        return { status: r.status, body: (await r.json()) as { addressed?: boolean; text?: string } };
      };
      const ask = async (conversationId: string, text: string) => {
        const r = await fetch(`${base}/api/conversations/${conversationId}/messages`, { method: "POST", headers: { ...auth, "content-type": "application/json" }, body: JSON.stringify({ content: text, inputMode: "voice" }) });
        return (await r.text()).split("\n\n").filter((l) => l.startsWith("data: ")).map((l) => JSON.parse(l.slice(6))).filter((e) => e.type === "delta").map((e) => e.text).join("");
      };
      const speak = async (text: string) => {
        const r = await fetch(`${base}/api/voice/speak`, { method: "POST", headers: { ...auth, "content-type": "application/json" }, body: JSON.stringify({ text }) });
        return { status: r.status, bytes: (await r.arrayBuffer()).byteLength };
      };

      expect((await fetch(`${base}/api/voice/handsfree`, { method: "POST", headers: { ...auth, "content-type": "application/json" }, body: JSON.stringify({ enabled: true }) })).ok).toBe(true);
      log("hands-free on");
      const conv = ((await (await fetch(`${base}/api/conversations`, { method: "POST", headers: auth })).json()) as { conversation: { id: string } }).conversation.id;

      // Negative control: speech not addressed to ULTRON is discarded.
      const ignored = await hear(notForUs, true);
      log(`not addressed → ${JSON.stringify(ignored.body)}`);
      expect(ignored.body.addressed).toBe(false);

      // Positive control: addressed speech is understood, answered and spoken.
      const heard = await hear(addressed, true);
      log(`addressed → ${JSON.stringify(heard.body)}`);
      expect(heard.body.addressed).toBe(true);
      expect(heard.body.text?.toLowerCase()).toContain("time");
      const reply = await ask(conv, heard.body.text!);
      log(`reply: ${reply.slice(0, 80)}`);
      expect(reply.length).toBeGreaterThan(0);
      const spoken = await speak(reply);
      log(`spoken: ${spoken.status} ${spoken.bytes} bytes`);
      expect(spoken.status).toBe(200);
      expect(spoken.bytes).toBeGreaterThan(10_000);

      // Follow-up without the wake word (conversation mode).
      const follow = await hear(followUp, false);
      log(`follow-up → ${JSON.stringify(follow.body)}`);
      expect(follow.status).toBe(200);
      expect((follow.body.text ?? "").toLowerCase()).toContain("time");
      expect((await ask(conv, follow.body.text!)).length).toBeGreaterThan(0);

      // The speech model crashes mid-conversation (or runs out of memory): ULTRON stays up and the next phrase still works.
      const helpers = childPids(server.pid!);
      log(`model processes: ${helpers.join(",")}`);
      expect(helpers.length).toBeGreaterThanOrEqual(1);
      for (const p of helpers) {
        try {
          process.kill(p, "SIGKILL");
        } catch (err) {
          if ((err as NodeJS.ErrnoException).code !== "ESRCH") throw err; // already gone (a short-lived helper): fine
        }
      }
      const afterCrash = await hear(addressed, true);
      log(`after model crash → ${JSON.stringify(afterCrash.body)}`);
      expect(afterCrash.body.addressed).toBe(true);

      // Positive control: online the whole time.
      monitoring = false;
      await monitor;
      log(`health: ${health.checks} checks, ${health.failures} failures, slowest ${health.maxMs} ms`);
      expect(health.checks).toBeGreaterThan(10);
      expect(health.failures).toBe(0);
      expect(health.maxMs).toBeLessThan(1500);

      // Negative control for the monitor itself: stop the service and the same check must notice within 3 s.
      server.kill("SIGKILL");
      let noticed = false;
      for (let i = 0; i < 12 && !noticed; i++) {
        noticed = !(await fetch(`${base}/api/health`, { signal: AbortSignal.timeout(2000) }).then((r) => r.ok, () => false));
        if (!noticed) await new Promise((r) => setTimeout(r, 250));
      }
      log(`monitor noticed the outage: ${noticed}`);
      expect(noticed).toBe(true);
    } finally {
      ciNote("Hands-free trace (real models)", trace.join(" | "));
      server.kill("SIGKILL");
    }
  }, 1_800_000);
});
